        $dbHost = trim($_POST['db_host'] ?? 'localhost');
        $dbName = trim($_POST['db_name'] ?? 'freedns');
        $dbUser = trim($_POST['db_user'] ?? 'root');
        $dbPass = $_POST['db_pass'] ?? '';

        try {
            $pdo = new PDO("mysql:host=$dbHost;charset=utf8mb4", $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            ]);

            $pdo->exec("CREATE DATABASE IF NOT EXISTS `$dbName` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            $pdo->exec("USE `$dbName`");

            $schema = file_get_contents(__DIR__ . '/schema.sql');
            $schema = preg_replace('/^.*?CREATE DATABASE.*?;/ms', '', $schema);
            $schema = str_replace('USE freedns;', '', $schema);
            $schema = str_replace('freedns', $dbName, $schema);

            $statements = array_filter(array_map('trim', explode(';', $schema)), fn($s) => $s !== '');
            foreach ($statements as $sql) {
                $pdo->exec($sql);
            }

            $_SESSION['install'] = [
                'db_host' => $dbHost,
                'db_name' => $dbName,
                'db_user' => $dbUser,
                'db_pass' => $dbPass,
