                $configContent .= "// ---- Security / limits ----\n";
                $configContent .= "define('SUB_MAX_LENGTH', 63);\n";
                $configContent .= "define('MIN_PASSWORD', 8);\n";
                $configContent .= "define('CSRF_SECRET', " . var_export($csrfSecret, true) . ");\n";

                file_put_contents(__DIR__ . '/includes/config.php', $configContent);

